import random

def generate_novel(scenario):
    intro = "これはあなただけの特別な恋の物語です。\n\n"
    if scenario == "復縁":
        body = (
            "別れたあの日からずっと彼を思い続けたあなた。\n"
            "街ですれ違うたびに胸が痛んで、夜はひとりで泣いていた。\n"
            "でも、ある日突然彼から連絡が来た——『会えないかな？』\n"
            "待ち合わせ場所に現れた彼は、少し痩せて、でも優しい笑顔で\n"
            "『やっぱり、君じゃなきゃだめなんだ』と告げる。\n"
            "涙ぐむあなたをそっと抱き寄せ、再び始まる二人の物語——。\n"
            "カフェで向かい合い、少しぎこちない会話。\n"
            "でも、目が合うと自然に笑顔がこぼれ、ふたりは少しずつ距離を縮めていく。\n"
            "やがて彼がそっと手を伸ばし、あなたの手を包む。\n"
            "『もう二度と離さない』、その言葉が胸に響き、涙が止まらなくなる。\n"
        )
    elif scenario == "職場恋愛":
        body = (
            "オフィスの中、いつも真剣な表情で働く彼。\n"
            "最初は怖い人かと思っていたけれど、何度か助けてもらううちに\n"
            "少しずつ優しい一面が見えてきた。\n"
            "ある日遅くまで残業していると、彼が差し入れを持ってきてくれた。\n"
            "『頑張りすぎるなよ』——その一言に胸が高鳴る。\n"
            "気づけば二人きりのオフィス、静寂の中で見つめ合うふたり。\n"
            "彼がそっと近づき、耳元でささやく。\n"
            "『……好きだ』\n"
            "驚きと嬉しさで心臓が爆発しそうになるあなた。\n"
            "その夜から、ふたりの秘密の恋が始まった——。\n"
        )
    elif scenario == "同棲":
        body = (
            "朝、目を覚ますと彼の寝顔がすぐ隣にある幸せ。\n"
            "休日には一緒に料理をして、ソファで映画を観て、猫のようにくっついて眠る夜。\n"
            "ケンカして泣いた日も、彼がそっと後ろから抱きしめて『ごめん』と謝ってくれる。\n"
            "洗面所に並ぶ歯ブラシ、冷蔵庫に貼ったメモ、寝る前の『おやすみ』のキス——\n"
            "すべてが愛おしい、ふたりの日常。\n"
            "これから先も、ずっとこんなふうに隣で笑い合っていたい。\n"
        )
    elif scenario == "デート":
        body = (
            "初めての遊園地デート。\n"
            "ジェットコースターで手をつないで大笑いし、観覧車ではドキドキの沈黙。\n"
            "お揃いのカチューシャを買って、写真を撮って、プリクラを貼った手帳を見返して笑う。\n"
            "帰り道、夕焼けの中で彼がそっと手を握りしめる。\n"
            "『今日、一番楽しかったのは……君と一緒にいた時間だよ』\n"
            "あなたの頬が赤く染まり、彼は満足そうに微笑む。\n"
        )
    elif scenario == "プロポーズ":
        body = (
            "高級レストランでディナーを終えた後、夜景の見える公園へ。\n"
            "突然彼が立ち止まり、あなたを見つめる。\n"
            "『実は、ずっと伝えたいことがあったんだ』\n"
            "震える手で小さな箱を取り出し、ひざまずく彼。\n"
            "『結婚してください』——瞳を潤ませるあなた。\n"
            "指輪が指にはまった瞬間、二人は幸せに包まれ、涙と笑顔があふれた。\n"
        )
    elif scenario == "結婚":
        body = (
            "結婚式の日、純白のドレスに身を包んだあなたを見て、彼は思わず息を呑む。\n"
            "『きれいだ……』とつぶやき、そっと手を伸ばす。\n"
            "指輪交換、誓いのキス、祝福のシャワー。\n"
            "ふたりの未来が、まぶしいほどに輝いて見える。\n"
            "これからどんなことがあっても、彼と一緒なら乗り越えられる。\n"
            "世界でいちばん大好きな人と、これからの人生を共に歩む——それが最高の幸せ。\n"
        )
    else:
        body = "申し訳ありません、そのシナリオはまだ準備中です。"

    outro = "\nこれからもふたりの物語は続いていきます。あなたの幸せを心から願っています。"

    return intro + body + outro

# 使用例
if __name__ == "__main__":
    print("シナリオを選んでください: 復縁 / 職場恋愛 / 同棲 / デート / プロポーズ / 結婚")
    choice = input("選択: ")
    print("\n" + generate_novel(choice))